import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
const root = path.resolve(import.meta.dirname, "..");
const fixture = fs.mkdtempSync(path.join(root, "artifacts", "rights-gate-"));
const write = (file, content) => { const target = path.join(fixture, file); fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); };
write("scripts/check-release-rights.mjs", fs.readFileSync(path.join(root, "scripts/check-release-rights.mjs")));
for (const file of ["data/gaia-signals.json", "data/gbif-rights.json", "docs/media-rights-ledger.json", "docs/THIRD_PARTY_INVENTORY.json", "package-lock.json", "sensor-platform/package-lock.json"]) write(file, "{}\n");
write("docs/decision.md", "Synthetic test evidence. Not a real publication approval.\n");
const ids = ["gosat", "unesco", "gbif", "jaxa-fnf-image", "generated-images-music", "remaining-data-and-software"];
const review = { schemaVersion: 1, reviews: ids.map(id => ({ id, status: "review-required", evidence: "docs/decision.md", requiredAction: "Synthetic fixture" })) };
const run = (state, args = []) => {
  write("docs/rights-review.json", JSON.stringify(state));
  return spawnSync(process.execPath, [path.join(fixture, "scripts/check-release-rights.mjs"), ...args], { cwd: fixture, encoding: "utf8", windowsHide: true });
};
const blocked = run(review); assert.equal(blocked.status, 1);
assert.equal(run(review, ["--validate"]).status, 0);
const scopeSha256 = JSON.parse(blocked.stdout).scopeSha256;
const approved = { ...review, reviews: review.reviews.map(row => ({ ...row, status: "approved", scopeSha256, decidedBy: "test fixture", decidedAt: "2026-09-07", decisionEvidence: "docs/decision.md" })) };
assert.equal(run(approved).status, 0, "exact scope and evidence should be accepted in the synthetic fixture");
write("data/gaia-signals.json", '{"changed":true}\n');
assert.notEqual(run(approved).status, 0, "data changes must invalidate old decisions");
write("data/gaia-signals.json", "{}\n");
assert.equal(run({ ...approved, reviews: approved.reviews.map((row, index) => index ? row : { ...row, status: "excluded" }) }).status, 1, "status alone must not exclude public files");
assert.notEqual(run({ ...approved, reviews: approved.reviews.slice(1) }).status, 0);
assert.notEqual(run({ ...approved, reviews: approved.reviews.map(row => ({ ...row, decisionEvidence: "missing.md" })) }).status, 0);
const ownerAccepted = { ...approved, reviews: approved.reviews.map(row => ({ ...row, status: "owner-accepted", decisionBasis: "Synthetic owner decision, not provider permission.", providerPermissionVerified: false })) };
const cleared = run(ownerAccepted);
assert.equal(cleared.status, 0, "a documented owner decision must clear the operational hold");
assert.equal(JSON.parse(cleared.stdout).status, "release-cleared");
assert(JSON.parse(cleared.stdout).ownerAccepted.every(row => row.providerPermissionVerified === false));
const mixed = run({ ...review, reviews: review.reviews.map(row => row.id === "gosat" ? ownerAccepted.reviews[0] : row) });
assert.equal(mixed.status, 1, "accepting GOSAT alone must not clear other reviews");
assert.deepEqual(JSON.parse(mixed.stdout).unresolved.map(row => row.id), ids.slice(1));
write("data/gaia-signals.json", '{"changed":true}\n');
assert.notEqual(run(ownerAccepted).status, 0, "data changes must invalidate old owner decisions too");
write("data/gaia-signals.json", "{}\n");
for (const field of ["decisionEvidence", "decidedBy", "decidedAt", "decisionBasis"]) {
  assert.notEqual(run({ ...ownerAccepted, reviews: ownerAccepted.reviews.map(row => ({ ...row, [field]: "" })) }).status, 0, `owner acceptance needs ${field}`);
}
assert.notEqual(run({ ...ownerAccepted, reviews: ownerAccepted.reviews.map(row => ({ ...row, providerPermissionVerified: true })) }).status, 0, "owner acceptance must not claim verified provider permission");
assert.notEqual(run({ ...ownerAccepted, reviews: ownerAccepted.reviews.map(row => ({ ...row, decisionEvidence: "missing.md" })) }).status, 0);
const excludedPath = "assets/data/jaxa-fnf-riau.png";
const afterRemoval = { ...approved, reviews: approved.reviews.map(row => row.id === "jaxa-fnf-image" ? { ...row, excludedPaths: [excludedPath] } : row) };
assert.equal(run(afterRemoval).status, 0, "an approved remaining scope may record an absent file");
write(excludedPath, "synthetic removed image");
assert.notEqual(run(afterRemoval).status, 0, "reintroduced files must invalidate the exclusion even before ledger regeneration");
fs.unlinkSync(path.join(fixture, excludedPath));
write("docs/media-rights-ledger.json", JSON.stringify({ assets: [{ path: excludedPath }] }));
const changedScope = JSON.parse(run(review).stdout).scopeSha256;
assert.notEqual(run({ ...afterRemoval, reviews: afterRemoval.reviews.map(row => ({ ...row, scopeSha256: changedScope })) }).status, 0, "a removed file must also be absent from a freshly scoped ledger");
write("docs/media-rights-ledger.json", "{}\n");
assert.notEqual(run({ ...afterRemoval, reviews: afterRemoval.reviews.map(row => row.excludedPaths ? { ...row, excludedPaths: ["../outside.png"] } : row) }).status, 0, "exclusions must stay within the repository");
assert.notEqual(run({ ...afterRemoval, reviews: afterRemoval.reviews.map(row => row.excludedPaths ? { ...row, excludedPaths: [] } : row) }).status, 0);
console.log(JSON.stringify({ status: "passed", tests: 21, fixtureOnly: true, productionReviewUnchanged: true }));
