import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
const hashes = new Set();
for (const file of ["index.html", "sensors/index.html", "concept/index.html"]) {
  const html = fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n?/g, "\n");
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (/\bsrc\s*=/i.test(attrs) || /\btype\s*=\s*["']application\/ld\+json/i.test(attrs)) continue;
    hashes.add(`'sha256-${createHash("sha256").update(body).digest("base64")}'`);
  }
}
// User-selected BYOK destinations need HTTPS connect-src. No arbitrary remote
// script execution; executable inline scripts are bound to exact build hashes.
const policy = ["default-src 'self'", `script-src 'self' https://www.googletagmanager.com ${[...hashes].sort().join(" ")}`,
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com", "font-src 'self' data: https://fonts.gstatic.com",
  "img-src 'self' data: blob: https:", "media-src 'self' blob:",
  "connect-src 'self' https: wss: http://localhost:* http://127.0.0.1:*",
  "worker-src 'self' blob:", "object-src 'none'", "base-uri 'self'", "form-action 'self'", "frame-ancestors 'none'"].join("; ");
const headers = { "Content-Security-Policy": policy, "X-Content-Type-Options": "nosniff", "X-Frame-Options": "DENY", "Referrer-Policy": "strict-origin-when-cross-origin" };
const generated = `// Generated by scripts/build-browser-security.mjs; do not edit.\nexport const browserSecurityHeaders = ${JSON.stringify(headers, null, 2)};\n`;
const headerPath = path.join(root, "_headers");
const marker = "# BEGIN generated browser security";
const original = fs.readFileSync(headerPath, "utf8").replace(/\r\n/g, "\n");
const base = original.split(marker)[0].trimEnd();
const output = `${base}\n\n${marker}\n/*\n${Object.entries(headers).map(([key, value]) => `  ${key}: ${value}`).join("\n")}\n# END generated browser security\n`;
for (const [target, content] of [[headerPath, output], [path.join(root, "sensor-platform/src/browser-security.ts"), generated]]) {
  if (check) assert.equal(fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n"), content, `Stale security policy: ${target}`);
  else fs.writeFileSync(target, content);
}
console.log(JSON.stringify({ status: check ? "passed" : "generated", inlineScriptHashes: hashes.size }));
