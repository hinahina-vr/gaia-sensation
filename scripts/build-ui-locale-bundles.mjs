// Git's autocrlf may rewrite source and generated files on checkout. Compare
// canonical newlines so a clean Windows checkout is not reported as stale.
const normalizeNewlines = text => text.replace(/\r\n/g, '\n');
const sources = originalOrder.map(name => normalizeNewlines(fs.readFileSync(path.join('locales', name + '.js'), 'utf8')));
const collect = source => {
  const rows = [];
  const runtime = { register: entries => rows.push(...JSON.parse(JSON.stringify(entries))) };
  vm.runInNewContext(source, { GaiaI18n: runtime, window: { GaiaI18n: runtime } }, { timeout: 1000 });
  return rows;
};
const content = '// Generated by scripts/build-ui-locale-bundles.mjs; edit the source catalogs.\n'
  + '(() => {\nconst entries = [];\nconst GaiaI18n = { register: rows => entries.push(...rows) };\n'
  + 'const window = { GaiaI18n };\n'
  + sources.join('\n;\n')
  + '\n;globalThis.GaiaI18n.register(entries);\n})();\n';
const expected = sources.flatMap(collect);
assert.deepEqual(collect(content), expected, 'Translations and precedence must remain identical');
const target = 'locales/ui-entry.bundle.js';
if (process.argv.includes('--check')) assert.equal(normalizeNewlines(fs.readFileSync(target, 'utf8')), content, target + ' is stale');
else fs.writeFileSync(target, content);
console.log(originalOrder.length + ' catalogs bundled; ' + expected.length + ' ordered entries verified; ' + Buffer.byteLength(content) + ' bytes');
