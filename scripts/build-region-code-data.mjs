import path from "node:path";
import process from "node:process";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUTPUT = path.join(ROOT, "sensor-platform", "src", "region-code-data.ts");
const CLDR_VERSION = "48.2.0";
const DATASET_DATE = "2026-08-14";
const checkOnly = process.argv.includes("--check");

const PREFECTURES = [
  ["01", "北海道"], ["02", "青森県"], ["03", "岩手県"], ["04", "宮城県"], ["05", "秋田県"],
  ["06", "山形県"], ["07", "福島県"], ["08", "茨城県"], ["09", "栃木県"], ["10", "群馬県"],
  ["11", "埼玉県"], ["12", "千葉県"], ["13", "東京都"], ["14", "神奈川県"], ["15", "新潟県"],
  ["16", "富山県"], ["17", "石川県"], ["18", "福井県"], ["19", "山梨県"], ["20", "長野県"],
  ["21", "岐阜県"], ["22", "静岡県"], ["23", "愛知県"], ["24", "三重県"], ["25", "滋賀県"],
  ["26", "京都府"], ["27", "大阪府"], ["28", "兵庫県"], ["29", "奈良県"], ["30", "和歌山県"],
  ["31", "鳥取県"], ["32", "島根県"], ["33", "岡山県"], ["34", "広島県"], ["35", "山口県"],
  ["36", "徳島県"], ["37", "香川県"], ["38", "愛媛県"], ["39", "高知県"], ["40", "福岡県"],
  ["41", "佐賀県"], ["42", "長崎県"], ["43", "熊本県"], ["44", "大分県"], ["45", "宮崎県"],
  ["46", "鹿児島県"], ["47", "沖縄県"],
];

const JLIS_ROOT = "https://www.j-lis.go.jp";
const JLIS_HOKKAIDO = `${JLIS_ROOT}/spd/code-address/hokkaido/cms_12214179.html`;
const JLIS_INDEXES = [
  `${JLIS_ROOT}/spd/code-address/touhoku/cms_1014180.html`,
  `${JLIS_ROOT}/spd/code-address/kantou/cms_1014181.html`,
  `${JLIS_ROOT}/spd/code-address/tyuubu/cms_1014182.html`,
  `${JLIS_ROOT}/spd/code-address/kinki/cms_1014183.html`,
  `${JLIS_ROOT}/spd/code-address/chuugoku/cms_1014184.html`,
  `${JLIS_ROOT}/spd/code-address/shikoku/cms_1014186.html`,
  `${JLIS_ROOT}/spd/code-address/kyuusyuu/cms_1014187.html`,
];

const [labelsDocument, territoryDocument, containmentDocument, municipalities] = await Promise.all([
  fetchJson(`https://unpkg.com/cldr-subdivisions-full@${CLDR_VERSION}/subdivisions/en/en.json`),
  fetchJson(`https://unpkg.com/cldr-localenames-full@${CLDR_VERSION}/main/en/territories.json`),
  fetchJson(`https://unpkg.com/cldr-core@${CLDR_VERSION}/supplemental/subdivisionContainment.json`),
  loadMunicipalities(),
]);

const labels = labelsDocument.subdivisions.localeDisplayNames.subdivisions;
const territoryNames = territoryDocument.main.en.localeDisplayNames.territories;
const labelFallbacks = { cnnm: "Inner Mongolia", fi01: "Åland" };
const containment = containmentDocument.supplemental.subdivisionContainment;
const subdivisions = [];
for (const countryCode of Object.keys(containment).filter((key) => /^[A-Z]{2}$/u.test(key)).sort()) {
  const codes = collectContainedCodes(containment, countryCode);
  for (const compactCode of codes) {
    const suffix = compactCode.slice(2).toUpperCase();
    const name = labels[compactCode] ?? labelFallbacks[compactCode] ?? (suffix.length === 2 ? territoryNames[suffix] : undefined);
    if (typeof name !== "string") throw new Error(`CLDR display name is missing for ${compactCode}.`);
    subdivisions.push([toIsoSubdivision(compactCode), countryCode, name]);
  }
}

const prefectureNames = Object.fromEntries(PREFECTURES.map(([digits, name]) => [`JP-${digits}`, name]));
for (const subdivision of subdivisions) {
  const japaneseName = prefectureNames[subdivision[0]];
  if (japaneseName) subdivision[2] = japaneseName;
}
subdivisions.sort((left, right) => left[0].localeCompare(right[0], "en"));
municipalities.sort((left, right) => left[0].localeCompare(right[0], "en"));

if (subdivisions.length < 4_500) throw new Error(`Unexpectedly small CLDR subdivision registry: ${subdivisions.length}.`);
if (municipalities.length < 1_800) throw new Error(`Unexpectedly small J-LIS municipality registry: ${municipalities.length}.`);

const source = `/* This file is generated by scripts/build-region-code-data.mjs. */
/* Sources: Unicode CLDR ${CLDR_VERSION}; J-LIS municipality pages read ${DATASET_DATE}. */
export const REGION_DATA_VERSION = ${JSON.stringify(`cldr-${CLDR_VERSION}+jlis-${DATASET_DATE}`)};

export const SUBDIVISION_RECORDS: readonly (readonly [code: string, countryCode: string, name: string])[] = ${formatRecords(subdivisions)};

export const JAPAN_MUNICIPALITY_RECORDS: readonly (readonly [code: string, subdivisionCode: string, name: string])[] = ${formatRecords(municipalities)};
`;

if (checkOnly) {
  if (!fs.existsSync(OUTPUT) || fs.readFileSync(OUTPUT, "utf8") !== source) {
    throw new Error("region-code-data.ts is stale. Run node scripts/build-region-code-data.mjs.");
  }
  console.log(JSON.stringify({ status: "passed", subdivisions: subdivisions.length, municipalities: municipalities.length }));
} else {
  fs.writeFileSync(OUTPUT, source, "utf8");
  console.log(JSON.stringify({ status: "generated", output: path.relative(ROOT, OUTPUT), subdivisions: subdivisions.length, municipalities: municipalities.length }));
}

async function loadMunicipalities() {
  const indexDocuments = await Promise.all(JLIS_INDEXES.map((url) => fetchText(url)));
  const prefectureUrls = new Map([["01", JLIS_HOKKAIDO]]);
  for (const [digits, prefectureName] of PREFECTURES.slice(1)) {
    const link = indexDocuments.flatMap(extractLinks).find(({ text }) => text.includes(prefectureName));
    if (!link) throw new Error(`J-LIS municipality page was not found for ${prefectureName}.`);
    prefectureUrls.set(digits, new URL(link.href, JLIS_ROOT).href);
  }
  const pages = await Promise.all(PREFECTURES.map(async ([digits, prefectureName]) => ({
    digits,
    prefectureName,
    html: await fetchText(prefectureUrls.get(digits)),
  })));
  const records = [];
  for (const { digits, prefectureName, html } of pages) {
    const pageRecords = extractTableRows(html).flatMap((cells) => {
      const code = cells[0] ?? "";
      const name = cells[1] ?? "";
      if (!/^\d{6}$/u.test(code)) return [];
      if (!code.startsWith(digits)) throw new Error(`${prefectureName} contains an unexpected code ${code}.`);
      if (!hasValidMunicipalityCheckDigit(code)) throw new Error(`J-LIS code has an invalid check digit: ${code}.`);
      if (!name) throw new Error(`J-LIS municipality name is missing for ${code}.`);
      return [[code, `JP-${digits}`, name]];
    });
    if (pageRecords.length < 4) throw new Error(`No municipality table found for ${prefectureName}.`);
    records.push(...pageRecords);
  }
  if (new Set(records.map(([code]) => code)).size !== records.length) throw new Error("J-LIS municipality codes are not unique.");
  return records;
}

function formatRecords(records) {
  return `[\n${records.map((record) => `  ${JSON.stringify(record)}`).join(",\n")}\n]`;
}

function collectContainedCodes(containment, root) {
  const found = new Set();
  const visit = (key) => {
    for (const child of containment[key]?._contains ?? []) {
      if (found.has(child)) continue;
      found.add(child);
      visit(child);
    }
  };
  visit(root);
  return [...found].sort();
}

function toIsoSubdivision(compactCode) {
  if (!/^[a-z]{2}[a-z0-9]{1,3}$/u.test(compactCode)) throw new Error(`Unexpected CLDR subdivision key: ${compactCode}.`);
  return `${compactCode.slice(0, 2).toUpperCase()}-${compactCode.slice(2).toUpperCase()}`;
}

function hasValidMunicipalityCheckDigit(code) {
  const digits = [...code].map(Number);
  const weighted = digits.slice(0, 5).reduce((sum, digit, index) => sum + digit * (6 - index), 0);
  return digits[5] === (11 - (weighted % 11)) % 10;
}

function extractLinks(html) {
  return [...html.matchAll(/<a\b[^>]*href\s*=\s*["']([^"']+)["'][^>]*>([\s\S]*?)<\/a>/giu)]
    .map((match) => ({ href: decodeHtml(match[1] ?? ""), text: cleanHtml(match[2] ?? "") }));
}

function extractTableRows(html) {
  return [...html.matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/giu)].map((row) =>
    [...(row[1] ?? "").matchAll(/<t[dh]\b[^>]*>([\s\S]*?)<\/t[dh]>/giu)].map((cell) => cleanHtml(cell[1] ?? "")),
  );
}

function cleanHtml(value) {
  return decodeHtml(value.replace(/<br\s*\/?\s*>/giu, " ").replace(/<[^>]+>/gu, " ")).replace(/\s+/gu, " ").trim();
}

function decodeHtml(value) {
  return value
    .replace(/&nbsp;|&#160;/giu, " ")
    .replace(/&amp;/giu, "&")
    .replace(/&quot;/giu, '"')
    .replace(/&#39;|&apos;/giu, "'")
    .replace(/&lt;/giu, "<")
    .replace(/&gt;/giu, ">")
    .replace(/&#(\d+);/gu, (_, digits) => String.fromCodePoint(Number(digits)))
    .replace(/&#x([0-9a-f]+);/giu, (_, digits) => String.fromCodePoint(Number.parseInt(digits, 16)));
}

async function fetchJson(url) {
  return JSON.parse(await fetchText(url));
}

async function fetchText(url) {
  if (!url) throw new Error("Source URL is missing.");
  const response = await fetch(url, { headers: { "User-Agent": "GAIA-SENSEWARE-region-data-generator/1.0" } });
  if (!response.ok) throw new Error(`Could not read ${url}: HTTP ${response.status}.`);
  return response.text();
}
